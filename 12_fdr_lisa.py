# -*- coding: utf-8 -*-
"""
12_fdr_lisa.py  —  FDR-Adjusted LISA Clusters
-----------------------------------------------
Applies Benjamini-Hochberg False Discovery Rate (FDR) correction to the
local Moran p-values from LISA analysis (province-mean cross-section).

Addresses Reviewer 2's request for multiple-testing correction on LISA
p-values (81 simultaneous tests).

Outputs:
  12_fdr_lisa_clusters.csv    — province-level: q, p_sim, p_fdr, sig_uncorr, sig_fdr
  12_fdr_lisa_report.txt      — comparison table + FDR threshold
"""

import os, sys
import numpy as np
import pandas as pd
from esda import Moran_Local
from statsmodels.stats.multitest import multipletests

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from data_loader import load_data, Y_COL, OUT_DIR, DATA_XLS

SEED = 42
FDR_ALPHA = 0.05

# ── Load data ─────────────────────────────────────────────────────────────────
df, w = load_data()
print(f"Data loaded: {len(df)} provinces")

y = df[Y_COL].values

# ── LISA on province means ─────────────────────────────────────────────────────
lisa = Moran_Local(y, w, permutations=999, geoda_quads=True, seed=SEED)

p_sim   = lisa.p_sim          # shape (n,)
q_vals  = lisa.q              # 1=HH, 2=LH, 3=LL, 4=HL

QUAD_LABEL = {0: "NS", 1: "HH", 2: "LH", 3: "LL", 4: "HL"}

# ── Uncorrected clusters (p < 0.05) ──────────────────────────────────────────
sig_uncorr  = p_sim < FDR_ALPHA
clusters_unc = np.where(sig_uncorr, q_vals, 0)

# ── Benjamini-Hochberg FDR correction ─────────────────────────────────────────
reject_fdr, p_fdr, _, _ = multipletests(p_sim, alpha=FDR_ALPHA, method="fdr_bh")
clusters_fdr = np.where(reject_fdr, q_vals, 0)

# ── Build comparison dataframe ────────────────────────────────────────────────
prov_order = [int(p) for p in w.id_order]
df_raw = pd.read_excel(DATA_XLS)
prov_names = df_raw[["PROV_ID","Province"]].drop_duplicates("PROV_ID").set_index("PROV_ID")["Province"]

rows = []
for i, pid in enumerate(prov_order):
    rows.append({
        "PROV_ID":    pid,
        "Province":   prov_names.get(pid, str(pid)),
        "q":          int(q_vals[i]),
        "p_sim":      float(p_sim[i]),
        "p_fdr":      float(p_fdr[i]),
        "cluster_unc": QUAD_LABEL.get(clusters_unc[i], "NS"),
        "cluster_fdr": QUAD_LABEL.get(clusters_fdr[i], "NS"),
        "sig_uncorr":  bool(sig_uncorr[i]),
        "sig_fdr":     bool(reject_fdr[i]),
    })

out_df = pd.DataFrame(rows)
out_df.to_csv(os.path.join(OUT_DIR, "12_fdr_lisa_clusters.csv"), index=False)
print(f"Saved: {os.path.join(OUT_DIR, '12_fdr_lisa_clusters.csv')}")

# ── Summary counts ─────────────────────────────────────────────────────────────
def count_clusters(arr):
    s = pd.Series(arr)
    return {lbl: (s == lbl).sum() for lbl in ["HH","LH","LL","HL","NS"]}

cnt_unc = count_clusters(out_df["cluster_unc"])
cnt_fdr = count_clusters(out_df["cluster_fdr"])

# FDR critical threshold (largest p_sim where BH reject=True)
fdr_pvals_rejected = p_sim[reject_fdr]
fdr_threshold = float(fdr_pvals_rejected.max()) if len(fdr_pvals_rejected) > 0 else 0.0

# Provinces that change status
changed = out_df[out_df["cluster_unc"] != out_df["cluster_fdr"]].copy()

# ── Report ─────────────────────────────────────────────────────────────────────
SEP = "=" * 72
sep = "-" * 72

lines = [
    "FDR-ADJUSTED LISA CLUSTERS (Province Means)",
    "Generated by: 12_fdr_lisa.py",
    SEP,
    "Method: Moran_Local, 999 permutations, seed=42, geoda_quads=True",
    f"Multiple-testing correction: Benjamini-Hochberg FDR, alpha={FDR_ALPHA}",
    f"n = {w.n} provinces (81 simultaneous tests)",
    "",
    "CLUSTER COUNTS: UNCORRECTED vs FDR-ADJUSTED",
    sep,
    f"  {'Cluster':10s}  {'Uncorrected (p<0.05)':>22s}  {'FDR-adjusted':>14s}",
    sep,
]
for lbl in ["HH", "LH", "LL", "HL", "NS"]:
    lines.append(f"  {lbl:10s}  {cnt_unc[lbl]:>22d}  {cnt_fdr[lbl]:>14d}")
lines += [
    sep,
    f"  Total significant   {sum(v for k,v in cnt_unc.items() if k!='NS'):>22d}  "
    f"{sum(v for k,v in cnt_fdr.items() if k!='NS'):>14d}",
    "",
    f"  Effective FDR threshold (max rejected p_sim): {fdr_threshold:.4f}",
    "",
]

# Significant provinces (HH) both approaches
hh_unc = out_df[out_df["cluster_unc"] == "HH"].sort_values("p_sim")
hh_fdr = out_df[out_df["cluster_fdr"] == "HH"].sort_values("p_fdr")

lines += [
    "HH PROVINCES — UNCORRECTED (p < 0.05)",
    sep,
    f"  {'PROV_ID':>8s}  {'Province':<22s}  {'p_sim':>8s}  {'p_fdr':>8s}  {'FDR':>5s}",
    sep,
]
for _, r in hh_unc.iterrows():
    fdr_mark = "✅" if r["sig_fdr"] else "❌"
    lines.append(f"  {int(r.PROV_ID):>8d}  {r.Province:<22s}  {r.p_sim:>8.4f}  {r.p_fdr:>8.4f}  {fdr_mark}")

lines += [""]

# LH provinces
lh_unc = out_df[out_df["cluster_unc"] == "LH"].sort_values("p_sim")
if len(lh_unc):
    lines += [
        "LH PROVINCES — UNCORRECTED (p < 0.05)",
        sep,
        f"  {'PROV_ID':>8s}  {'Province':<22s}  {'p_sim':>8s}  {'p_fdr':>8s}  {'FDR':>5s}",
        sep,
    ]
    for _, r in lh_unc.iterrows():
        fdr_mark = "✅" if r["sig_fdr"] else "❌"
        lines.append(f"  {int(r.PROV_ID):>8d}  {r.Province:<22s}  {r.p_sim:>8.4f}  {r.p_fdr:>8.4f}  {fdr_mark}")
    lines.append("")

# Changed provinces
if len(changed):
    lines += [
        "PROVINCES THAT CHANGE STATUS (uncorrected → FDR)",
        sep,
        f"  {'Province':<22s}  {'Uncorrected':>12s}  {'FDR':>12s}  {'p_sim':>8s}  {'p_fdr':>8s}",
        sep,
    ]
    for _, r in changed.iterrows():
        lines.append(
            f"  {r.Province:<22s}  {r.cluster_unc:>12s}  {r.cluster_fdr:>12s}  "
            f"{r.p_sim:>8.4f}  {r.p_fdr:>8.4f}"
        )
else:
    lines.append("All significant clusters survive FDR correction unchanged.")

lines.append(SEP)

report_path = os.path.join(OUT_DIR, "12_fdr_lisa_report.txt")
with open(report_path, "w", encoding="utf-8") as fh:
    fh.write("\n".join(lines))

print("\n" + "\n".join(lines))
