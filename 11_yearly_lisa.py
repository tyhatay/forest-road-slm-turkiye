# -*- coding: utf-8 -*-
"""
11_yearly_lisa.py  —  Per-Year LISA Clusters + Province-by-Year Table
----------------------------------------------------------------------
Computes LISA clusters on the per-ha new road construction intensity
for each year 2017-2024 separately.

Outputs:
  11_yearly_lisa_table.csv    — province × year cluster labels
  11_yearly_lisa_report.txt   — summary + persistent clusters
"""

import os, sys
import numpy as np
import pandas as pd
from esda import Moran_Local

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from data_loader import load_data, Y_COL, OUT_DIR, DATA_XLS, load_weights, align_to_weights

# ── Correct quadrant mapping (esda geoda_quads=True) ─────────────────────────
QUAD_LABEL = {0: "NS", 1: "HH", 2: "LH", 3: "LL", 4: "HL"}

YEARS = list(range(2017, 2025))

# ── Load raw data ─────────────────────────────────────────────────────────────
df_raw = pd.read_excel(DATA_XLS)
for c in ["ArtStructure_km", "RoadMajorRepair_km", "RoadSurface_km"]:
    df_raw[c] = df_raw[c].fillna(0)
df_raw["NewRoad_kmha"] = df_raw["NewRoad_km"] / df_raw["Forest_Area_ha"]
df_raw = df_raw.fillna(0)

w = load_weights()
prov_order = [int(p) for p in w.id_order]
n = w.n
print(f"Weights matrix: {n} provinces")

# ── Province names lookup ─────────────────────────────────────────────────────
prov_names = df_raw[["PROV_ID","Province"]].drop_duplicates("PROV_ID").set_index("PROV_ID")["Province"]

# ── Per-year LISA ─────────────────────────────────────────────────────────────
SEED = 42
results = {}  # {year: array of cluster labels (0/1/2/3/4) aligned to prov_order}

for yr in YEARS:
    df_yr = df_raw[df_raw["Year"] == yr].copy()
    # align to weights matrix order
    df_yr = df_yr.set_index("PROV_ID")["NewRoad_kmha"].reindex(prov_order).fillna(0)
    y_yr  = df_yr.values

    lisa = Moran_Local(y_yr, w, permutations=999, geoda_quads=True, seed=SEED)
    clusters = np.where(lisa.p_sim < 0.05, lisa.q, 0)
    results[yr] = clusters
    n_hh = (clusters == 1).sum()
    n_ll = (clusters == 3).sum()
    print(f"  {yr}: HH={n_hh}  LL={n_ll}  LH={(clusters==2).sum()}  HL={(clusters==4).sum()}  NS={(clusters==0).sum()}")

# ── Build pivot table ─────────────────────────────────────────────────────────
rows = []
for i, pid in enumerate(prov_order):
    row = {"PROV_ID": pid, "Province": prov_names.get(pid, str(pid))}
    for yr in YEARS:
        row[str(yr)] = QUAD_LABEL[results[yr][i]]
    rows.append(row)

pivot = pd.DataFrame(rows)

# ── Identify persistent clusters ──────────────────────────────────────────────
# Count number of years in each cluster type
for label in ["HH", "LL", "LH", "HL"]:
    year_cols = [str(y) for y in YEARS]
    pivot[f"n_{label}"] = (pivot[year_cols] == label).sum(axis=1)

pivot["n_sig"] = pivot[[f"n_{lbl}" for lbl in ["HH","LL","LH","HL"]]].sum(axis=1)

# Provinces significant in 5+ years
persistent = pivot[pivot["n_sig"] >= 5].copy()

# ── Save ──────────────────────────────────────────────────────────────────────
out_csv = os.path.join(OUT_DIR, "11_yearly_lisa_table.csv")
pivot.to_csv(out_csv, index=False)
print(f"\nSaved: {out_csv}")

# ── Report ────────────────────────────────────────────────────────────────────
SEP = "=" * 72
sep = "-" * 72

lines = [
    "PER-YEAR LISA CLUSTERS (2017-2024)",
    "Generated by: 11_yearly_lisa.py",
    SEP,
    "Quadrant coding (geoda_quads=True): 1=HH, 2=LH, 3=LL, 4=HL; 0=NS",
    "p-threshold: 0.05 (999 permutations, seed=42)",
    "",
    "ANNUAL CLUSTER COUNTS",
    sep,
    f"  {'Year':>6s}  {'HH':>4s}  {'LL':>4s}  {'LH':>4s}  {'HL':>4s}  {'NS':>4s}",
    sep,
]
for yr in YEARS:
    c = results[yr]
    lines.append(f"  {yr:>6d}  {(c==1).sum():>4d}  {(c==3).sum():>4d}  {(c==2).sum():>4d}  {(c==4).sum():>4d}  {(c==0).sum():>4d}")

lines += [
    sep,
    "",
    "PERSISTENT HH PROVINCES (≥5 of 8 years)",
    sep,
]
hh_pers = pivot[pivot["n_HH"] >= 5][["PROV_ID","Province"] + [str(y) for y in YEARS] + ["n_HH"]].sort_values("n_HH", ascending=False)
for _, r in hh_pers.iterrows():
    years_hh = [str(y) for y in YEARS if r[str(y)] == "HH"]
    lines.append(f"  {int(r.PROV_ID):3d}  {r.Province:<20s}  HH in {r.n_HH}/8 years: {', '.join(years_hh)}")

lines += [
    "",
    "PERSISTENT LL PROVINCES (≥5 of 8 years)",
    sep,
]
ll_pers = pivot[pivot["n_LL"] >= 5][["PROV_ID","Province"] + [str(y) for y in YEARS] + ["n_LL"]].sort_values("n_LL", ascending=False)
for _, r in ll_pers.iterrows():
    years_ll = [str(y) for y in YEARS if r[str(y)] == "LL"]
    lines.append(f"  {int(r.PROV_ID):3d}  {r.Province:<20s}  LL in {r.n_LL}/8 years: {', '.join(years_ll)}")

# Hatay specifically
hatay_row = pivot[pivot["Province"].str.contains("Hatay|hatay", na=False, case=False)]
if len(hatay_row):
    hr = hatay_row.iloc[0]
    year_cols = [str(y) for y in YEARS]
    hatay_seq = " | ".join(f"{y}:{hr[str(y)]}" for y in YEARS)
    lines += [
        "",
        "HATAY — SPECIFIC SEQUENCE",
        sep,
        f"  {hatay_seq}",
        f"  n_HH = {int(hr.n_HH)}, n_LL = {int(hr.n_LL)}",
    ]

lines.append(SEP)

report_path = os.path.join(OUT_DIR, "11_yearly_lisa_report.txt")
with open(report_path, "w", encoding="utf-8") as fh:
    fh.write("\n".join(lines))

print("\n" + "\n".join(lines))
